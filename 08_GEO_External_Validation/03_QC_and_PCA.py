
"""
Sample QC and PCA using GEO logCPM generated by script 02.
No TMM inputs or normalization performed here.
"""

import numpy as np
import pandas as pd

import matplotlib
matplotlib.use("Agg")

import matplotlib.pyplot as plt

from sklearn.decomposition import PCA
from sklearn.preprocessing import StandardScaler

from config import *


# ------------------------------------------------------------
# 1. INPUT FILES
# ------------------------------------------------------------

raw_file = COUNT_DIR / "GSE58135_raw_counts_135samples.csv"

expr_file = HARM_DIR / "GEO_common_genes_logCPM_TCGA_matched.csv"

meta_file = INPUT_DIR / "GSE58135_metadata_135samples.csv"

QC_DIR.mkdir(parents=True, exist_ok=True)

for path in (raw_file, expr_file, meta_file):
    if not path.is_file():
        raise FileNotFoundError(
            f"Required input missing: {path}. "
            "Run scripts 01 and 02 first."
        )


# ------------------------------------------------------------
# 2. READ INPUT FILES
# ------------------------------------------------------------

print("\nReading GEO expression and metadata...")

raw = pd.read_csv(raw_file, index_col=0)

# FIX: pandas does not support check_names=False.
expr_df = pd.read_csv(expr_file)

meta = pd.read_csv(
    meta_file,
    dtype={"GSM_ID": str}
)

if "Gene_Symbol" not in expr_df.columns:
    raise ValueError(
        "Matched expression file must contain Gene_Symbol."
    )

if not {"GSM_ID", "Condition"}.issubset(meta.columns):
    raise ValueError(
        "Metadata must contain GSM_ID and Condition."
    )

meta["GSM_ID"] = meta["GSM_ID"].astype(str).str.strip()

meta = meta.set_index("GSM_ID")

expr = expr_df.set_index("Gene_Symbol")

print("Expression matrix:", expr.shape)
print("Raw count matrix:", raw.shape)
print("Metadata:", meta.shape)


# ------------------------------------------------------------
# 3. CHECK DUPLICATES
# ------------------------------------------------------------

if expr.columns.duplicated().any():
    raise ValueError("Duplicate sample IDs in expression matrix.")

if expr.index.duplicated().any():
    raise ValueError("Duplicate gene symbols in expression matrix.")

if meta.index.duplicated().any():
    raise ValueError("Duplicate GSM IDs in metadata.")

if raw.columns.duplicated().any():
    raise ValueError("Duplicate sample IDs in raw counts.")


# ------------------------------------------------------------
# 4. CHECK SAMPLE CONSISTENCY
# ------------------------------------------------------------

if set(expr.columns) != set(meta.index):
    raise ValueError(
        "Expression and metadata sample IDs do not match."
    )

if not set(raw.columns) >= set(meta.index):
    raise ValueError(
        "Raw count matrix does not contain all metadata samples."
    )

# Match metadata sample order.

expr = expr.loc[:, meta.index]

raw = raw.loc[:, meta.index]


# ------------------------------------------------------------
# 5. VALIDATE EXPRESSION AND RAW COUNTS
# ------------------------------------------------------------

expr = expr.apply(pd.to_numeric, errors="coerce")

raw = raw.apply(pd.to_numeric, errors="coerce")

if not np.isfinite(expr.to_numpy(dtype=float)).all():
    raise ValueError(
        "logCPM matrix contains NA/Inf/non-numeric values."
    )

if raw.isna().any().any():
    raise ValueError("Raw count matrix contains missing values.")

if not np.isfinite(raw.to_numpy(dtype=float)).all():
    raise ValueError("Raw count matrix contains non-finite values.")

if (raw.to_numpy() < 0).any():
    raise ValueError("Raw count matrix contains negative values.")

if not np.allclose(
    raw.to_numpy(),
    np.round(raw.to_numpy())
):
    raise ValueError("Raw count matrix is not integer-valued.")

if not meta["Condition"].isin(["Tumor", "Normal"]).all():
    raise ValueError("Unexpected condition labels.")


# ------------------------------------------------------------
# 6. SAMPLE QC SUMMARY
# ------------------------------------------------------------

print("\nCalculating sample QC metrics...")

# Raw library sizes are QC only.
# No normalization factors are estimated.

qc = pd.DataFrame({
    "GSM_ID": expr.columns,

    "Condition": meta.loc[
        expr.columns, "Condition"
    ].values,

    "Raw_Library_Size": raw.sum(axis=0).values,

    "Genes_Nonzero_logCPM": (
        expr > 0
    ).sum(axis=0).values,

    "Median_logCPM": expr.median(axis=0).values,

    "Mean_logCPM": expr.mean(axis=0).values
})

qc.to_csv(
    QC_DIR / "GSE58135_sample_QC_summary.csv",
    index=False
)


# ------------------------------------------------------------
# 7. BOXPLOT FUNCTION
# ------------------------------------------------------------

def save_box(values, xlabel, title, filename):

    plt.figure(figsize=(10, 5))

    plt.boxplot(
        values,
        vert=False,
        showfliers=False
    )

    plt.xlabel(xlabel)
    plt.title(title)

    plt.tight_layout()

    plt.savefig(
        QC_DIR / filename,
        dpi=300
    )

    plt.close()


# ------------------------------------------------------------
# 8. GENERATE QC BOXPLOTS
# ------------------------------------------------------------

print("\nGenerating QC plots...")

save_box(
    qc["Raw_Library_Size"],
    "Raw library size",
    "GSE58135 raw library sizes",
    "01_raw_library_sizes.png"
)

save_box(
    qc["Median_logCPM"],
    "Median logCPM",
    "GSE58135 median logCPM per sample",
    "02_median_logCPM.png"
)

save_box(
    qc["Genes_Nonzero_logCPM"],
    "Genes with logCPM > 0",
    "Detected genes per sample",
    "03_detected_genes.png"
)


# ------------------------------------------------------------
# 9. PCA USING TOP VARIABLE GENES
# ------------------------------------------------------------

print("\nPerforming PCA...")

# Select up to 3000 most variable genes.

variances = expr.var(axis=1, ddof=1)

variable = variances[
    np.isfinite(variances) & (variances > 0)
]

if len(variable) < 2:

    raise ValueError(
        "Fewer than two variable genes available for PCA."
    )

top_genes = variable.nlargest(
    min(3000, len(variable))
).index

X = expr.loc[top_genes].T

# Standardize genes across samples.

scaler = StandardScaler()

Xz = scaler.fit_transform(X)

ncomp = min(
    10,
    Xz.shape[0] - 1,
    Xz.shape[1]
)

if ncomp < 2:

    raise ValueError(
        "Not enough dimensions for PCA."
    )

pca = PCA(
    n_components=ncomp,
    random_state=42
)

coords = pca.fit_transform(Xz)


# ------------------------------------------------------------
# 10. SAVE PCA COORDINATES
# ------------------------------------------------------------

pca_df = pd.DataFrame(
    coords,
    index=X.index,
    columns=[
        f"PC{i+1}"
        for i in range(ncomp)
    ]
)

pca_df["Condition"] = meta.loc[
    pca_df.index, "Condition"
]

pca_df.to_csv(
    QC_DIR / "GSE58135_PCA_coordinates.csv"
)


# ------------------------------------------------------------
# 11. PCA SCATTER PLOT
# ------------------------------------------------------------

plt.figure(figsize=(9, 7))

for condition in ("Tumor", "Normal"):

    mask = pca_df["Condition"].eq(condition)

    plt.scatter(
        pca_df.loc[mask, "PC1"],
        pca_df.loc[mask, "PC2"],
        label=condition,
        alpha=0.8
    )

plt.xlabel(
    f"PC1 ({pca.explained_variance_ratio_[0] * 100:.1f}%)"
)

plt.ylabel(
    f"PC2 ({pca.explained_variance_ratio_[1] * 100:.1f}%)"
)

plt.title(
    "GSE58135 PCA after TCGA-matched logCPM"
)

plt.legend()

plt.tight_layout()

plt.savefig(
    QC_DIR / "04_PCA_Tumor_vs_Normal.png",
    dpi=300
)

plt.close()


# ------------------------------------------------------------
# 12. FINAL SUMMARY
# ------------------------------------------------------------

print("\n========================================")

print("GSE58135 QC AND PCA COMPLETED")

print("========================================")

print("Genes:", expr.shape[0])

print("Samples:", expr.shape[1])

print("Tumor:", (meta["Condition"] == "Tumor").sum())

print("Normal:", (meta["Condition"] == "Normal").sum())

print("PCA genes:", len(top_genes))

print("\nOutput directory:", QC_DIR)

print("\nGenerated files:")

for filename in [
    "GSE58135_sample_QC_summary.csv",
    "01_raw_library_sizes.png",
    "02_median_logCPM.png",
    "03_detected_genes.png",
    "GSE58135_PCA_coordinates.csv",
    "04_PCA_Tumor_vs_Normal.png"
]:

    print(" -", filename)

print("\n========================================")
